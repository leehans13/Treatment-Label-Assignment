#!/usr/bin/env Rscript
# Run from the repository root: Rscript src/schmidt/run.R [h5seurat] [cytokines] [output]
suppressPackageStartupMessages({library(tidyverse);library(SingleCellExperiment);library(data.table);library(Matrix)})
args <- commandArgs(trailingOnly = TRUE)
if (length(args) > 3L) stop("Usage: Rscript src/schmidt/run.R [h5seurat] [cytokines] [output]")
input <- if (length(args) >= 1L) args[1] else "data/schmidt/Perturb-seq/data/HuTcellsCRISPRaPerturbSeq_Re-stimulated.h5Seurat"
cytokines <- if (length(args) >= 2L) args[2] else "data/schmidt/Perturb-seq/data/GO_0005125_Cytokines.txt"
output <- if (length(args) >= 3L) args[3] else "data/schmidt/results"
options(degpaper.nebula.ncore = 1L)
source("src/common/methods.R")
source("src/common/helpers.R")
source("src/common/checkpoints.R")
source("src/schmidt/analysis.R")
dir.create(output, recursive = TRUE, showWarnings = FALSE)
x <- read_schmidt(input)
genes <- schmidt_genes(x$counts, x$metadata, cytokines)
message(length(genes$targets), " targets; ", length(genes$test), " test genes; ", length(genes$analysis), " candidate genes")
scripts <- c("src/common/methods.R", "src/common/helpers.R", "src/schmidt/analysis.R")
manifest <- make_manifest(c(input, cytokines), genes$targets, scripts,
                          extra = list(analysis_genes = genes$analysis, test_genes = genes$test))
# Existing Schmidt checkpoints were generated by the verified pre-refactor code.
legacy <- function(old, current) {
  expected_old <- c("8c9834479d59d2ecf801c2acf1e6fee0", "bc9fb03e7871a9724b7260bc8ec6c42a")
  expected_new <- c("8c9834479d59d2ecf801c2acf1e6fee0", "d9d70da413655505a6820497c64020c6", "46ea4ebc2957f0260452f194ad2edc95")
  identical(old$scripts, expected_old) && identical(current$scripts, expected_new) &&
    identical(old$paths, current$paths) && identical(old$sizes, current$sizes) &&
    identical(old$modified, current$modified) && identical(old$targets, current$units) &&
    identical(old$analysis_genes, current$extra$analysis_genes) &&
    identical(old$test_genes, current$extra$test_genes) &&
    identical(old$packages, current$packages) && identical(old$r_version, current$r_version) &&
    identical(old$nebula_ncore, current$nebula_ncore)
}
result <- checkpoint_map(genes$targets, output, manifest,
  compute = function(target) analyze_schmidt_target(x$counts, x$metadata, target, genes$analysis),
  valid = function(value) is.list(value) && length(value) == 6L,
  legacy = legacy)
saveRDS(result, file.path(output, "schdmidt.result.rds"))
summarize_schmidt(result, genes$targets, genes$test, output)
message("Wrote results to ", output)
